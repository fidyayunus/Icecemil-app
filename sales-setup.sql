-- ICE CEMIL: tabel khusus pencatatan penjualan
-- Jalankan sekali di Supabase Dashboard > SQL Editor > New query > Run.

create table if not exists public.sales_records (
  id bigint generated by default as identity primary key,
  sale_date date not null default current_date,
  menu_name text not null,
  unit_price integer not null check (unit_price >= 0),
  qty integer not null check (qty > 0),
  payment_method text not null check (payment_method in ('Tunai','QRIS')),
  buyer_type text not null check (buyer_type in ('Anak-anak','Remaja','Dewasa')),
  total integer not null check (total >= 0),
  created_at timestamptz not null default now()
);

alter table public.sales_records enable row level security;

-- Catatan: tanpa login, kebijakan ini mengizinkan siapa pun yang mengetahui
-- URL project/API publik untuk membaca, menambah, mengubah, dan menghapus data.
-- Jangan simpan data pribadi pelanggan pada tabel ini.
drop policy if exists "Public access sales records" on public.sales_records;
create policy "Public access sales records"
on public.sales_records
for all
to anon, authenticated
using (true)
with check (true);

grant select, insert, update, delete on public.sales_records to anon, authenticated;
grant usage, select on sequence public.sales_records_id_seq to anon, authenticated;
